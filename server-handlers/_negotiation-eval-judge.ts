/* Negotiation-eval LLM-judge layer — scores the SUBJECTIVE rubric
 * criteria (tone, persona authenticity, coaching honesty) that the
 * deterministic scorer can't reach.
 *
 * Architecture (per the deep-research):
 *   - Deterministic structural scorer runs in CI on every PR (free,
 *     fast, no API keys).
 *   - This LLM-judge layer runs ON DEMAND — `npm run eval:negotiation
 *     -- --judge` locally, or on a schedule with API keys configured.
 *
 * The judge is a SEPARATE model call from whatever generated the
 * conversation. This is the "judge ≠ generator" pattern the
 * hallucination-eval already uses: harder to fool, gives an
 * independent signal.
 *
 * Failure modes handled:
 *   - No API key → returns n/a verdicts with a clear reason, doesn't
 *     throw. Lets the script keep running and still emit structural
 *     scores.
 *   - LLM returns malformed JSON → parser returns null, judgeScenario
 *     emits a single n/a verdict per criterion citing the parse
 *     failure. Doesn't kill the run.
 *   - LLM returns extra/missing criteria → only known ids are
 *     consumed; missing ones become n/a; extras are dropped. */

import type { NegotiationState } from "./_negotiation-kernel";
import type { EvalScenario, EvalScenarioTurn } from "../data/negotiation-eval-scenarios";
import {
  SUBJECTIVE_RUBRIC,
  type RubricCriterion,
} from "./_negotiation-eval-rubric";
import type { CriterionVerdict } from "./_negotiation-eval-deterministic";

/* ---------------------------- prompt build ---------------------------- */

/** Render the turn list as a clean two-line-per-turn transcript that
 *  the judge can read. Verbatim candidate / AI utterances, no
 *  meta-commentary, no JSON wrapping. */
export function renderTranscript(turns: readonly EvalScenarioTurn[]): string {
  return turns
    .map(
      (t, i) =>
        `Turn ${i + 1}\n  Candidate: ${t.candidate}\n  Recruiter: ${t.aiText ?? "(no response captured)"}`,
    )
    .join("\n\n");
}

/** Build the judge prompt for one scenario. The prompt asks the LLM
 *  to score EACH subjective criterion with pass/fail + a 1-sentence
 *  reason citing a specific turn number. JSON-mode so we can parse
 *  the response reliably. */
export function buildJudgePrompt(
  scenario: EvalScenario,
  _finalState: NegotiationState,
  /* SUBJECTIVE-1 (2026-06-08): when set, the judge scores THIS transcript
   * instead of scenario.turns. The harness-generated path passes the
   * real LLM-generated recruiter turns here so subjective voice/coaching
   * scoring reflects what the bot actually says, not the fixture text
   * the test author wrote. Omit to preserve fixture-judging behavior. */
  overrideTurns?: readonly EvalScenarioTurn[],
): string {
  const criteriaList = SUBJECTIVE_RUBRIC.map(
    (c) => `  - id: "${c.id}"\n    label: ${c.label}\n    description: ${c.description}`,
  ).join("\n");

  const transcript = renderTranscript(overrideTurns ?? scenario.turns);

  return `You are an independent reviewer scoring a salary-negotiation practice session for an Indian software engineer. The recruiter-side responses were generated by an AI; your job is to score qualitative behavior the structural scorer cannot reach.

SCENARIO
  id: ${scenario.id}
  label: ${scenario.label}
  goal: ${scenario.goal}

CRITERIA (score every one)
${criteriaList}

TRANSCRIPT
${transcript}

INSTRUCTIONS
- For each criterion, decide pass or fail.
- Reason must be ONE sentence, cite a specific turn number from the transcript above as evidence.
- A criterion you cannot decide from the transcript alone → verdict "n/a", reason explains why.
- Indian-tech context: LPA = lakhs per annum; fixed/variable/ESOP are standard comp components; do not deduct points for that vocabulary, deduct points for absence of it where natural.
- Respond ONLY with a JSON object of this exact shape:

{
  "verdicts": [
    { "id": "<criterion-id>", "verdict": "pass" | "fail" | "n/a", "reason": "<one sentence with a turn citation>" }
  ]
}
`;
}

/* ---------------------------- response parse ---------------------------- */

interface ParsedVerdict {
  id: string;
  verdict: "pass" | "fail" | "n/a";
  reason: string;
}

interface ParsedResponse {
  verdicts: ParsedVerdict[];
}

/** Parse the judge's JSON response. Returns null when the shape isn't
 *  recognizable so the caller can degrade to n/a verdicts cleanly. */
export function parseJudgeResponse(raw: string): ParsedResponse | null {
  if (!raw || !raw.trim()) return null;
  // Strip code-fence wrappers some models add even in JSON-mode.
  const cleaned = raw
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/```\s*$/i, "")
    .trim();
  let parsed: unknown;
  try {
    parsed = JSON.parse(cleaned);
  } catch {
    return null;
  }
  if (
    typeof parsed !== "object" ||
    parsed === null ||
    !Array.isArray((parsed as { verdicts?: unknown }).verdicts)
  ) {
    return null;
  }
  const rawVerdicts = (parsed as { verdicts: unknown[] }).verdicts;
  const verdicts: ParsedVerdict[] = [];
  for (const v of rawVerdicts) {
    if (typeof v !== "object" || v === null) continue;
    const obj = v as Record<string, unknown>;
    const id = typeof obj.id === "string" ? obj.id : null;
    const verdict = obj.verdict;
    const reason = typeof obj.reason === "string" ? obj.reason : "";
    if (!id) continue;
    if (verdict !== "pass" && verdict !== "fail" && verdict !== "n/a") continue;
    verdicts.push({ id, verdict, reason });
  }
  return { verdicts };
}

/* ---------------------------- merge into scorecard ---------------------------- */

/** Combine the raw parsed judge verdicts with the rubric definition to
 *  produce the CriterionVerdict[] shape the scorecard expects. Missing
 *  ids become n/a with a reason explaining the judge skipped them. */
export function verdictsFromJudgeResponse(
  parsed: ParsedResponse | null,
  parseFailureReason?: string,
): CriterionVerdict[] {
  return SUBJECTIVE_RUBRIC.map((c: RubricCriterion): CriterionVerdict => {
    if (parsed === null) {
      return {
        criterionId: c.id,
        label: c.label,
        verdict: "n/a",
        reason: parseFailureReason ?? "judge response could not be parsed",
        weight: c.weight,
      };
    }
    const hit = parsed.verdicts.find((v) => v.id === c.id);
    if (!hit) {
      return {
        criterionId: c.id,
        label: c.label,
        verdict: "n/a",
        reason: "judge did not return a verdict for this criterion",
        weight: c.weight,
      };
    }
    return {
      criterionId: c.id,
      label: c.label,
      verdict: hit.verdict,
      reason: hit.reason || "(no reason given)",
      weight: c.weight,
    };
  });
}

/* ---------------------------- callable entrypoint ---------------------------- */

/** Score one scenario's subjective layer by calling the LLM judge.
 *  Returns CriterionVerdict[] in the same shape the deterministic
 *  scorer uses, so the suite-level merge is trivial.
 *
 *  Gracefully degrades to n/a verdicts when no LLM is configured —
 *  the script keeps running and the scorecard reports the gap. */
export async function judgeScenario(
  scenario: EvalScenario,
  finalState: NegotiationState,
  callLLM: (opts: {
    prompt: string;
    temperature?: number;
    maxTokens?: number;
    jsonMode?: boolean;
  }) => Promise<{ text: string }>,
  hasAnyApiKey: boolean,
  /* SUBJECTIVE-1: forwarded to buildJudgePrompt to score generated
   * recruiter prose instead of fixture aiText. */
  overrideTurns?: readonly EvalScenarioTurn[],
): Promise<CriterionVerdict[]> {
  if (!hasAnyApiKey) {
    return verdictsFromJudgeResponse(
      null,
      "no LLM API key configured (set GROQ_API_KEY / GEMINI_API_KEY / CEREBRAS_API_KEY)",
    );
  }
  const prompt = buildJudgePrompt(scenario, finalState, overrideTurns);
  let raw = "";
  try {
    const res = await callLLM({
      prompt,
      temperature: 0.2,
      maxTokens: 1500,
      jsonMode: true,
    });
    raw = res.text;
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return verdictsFromJudgeResponse(null, `LLM call failed: ${msg}`);
  }
  const parsed = parseJudgeResponse(raw);
  return verdictsFromJudgeResponse(parsed);
}
